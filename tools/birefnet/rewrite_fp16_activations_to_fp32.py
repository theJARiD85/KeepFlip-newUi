#!/usr/bin/env python3
"""Keep BiRefNet's FP16 weights while promoting graph activations to FP32.

The direct float16 export stores both weights and intermediate tensors as
FLOAT16. Some Android CPU fallback kernels reject those activation tensors.
This pass leaves constant weights encoded as FLOAT16, adds TFLite DEQUANTIZE
operators at their consumers, and promotes non-constant FLOAT16 tensors to
FLOAT32. The source artifact is never modified.

Requires numpy, flatbuffers, and the schema generated by onnx2tf 2.6.9.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Any

import flatbuffers
import numpy as np


def load_schema() -> Any:
    package = importlib.util.find_spec("onnx2tf")
    if package is None or not package.submodule_search_locations:
        raise RuntimeError("Install onnx2tf==2.6.9 to access its TFLite schema.")
    package_dir = Path(next(iter(package.submodule_search_locations)))
    schema_path = package_dir / "tflite_builder" / "schema" / "schema_generated.py"
    if not schema_path.is_file():
        raise RuntimeError(f"Generated TFLite schema not found: {schema_path}")
    spec = importlib.util.spec_from_file_location("onnx2tf_tflite_schema", schema_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Could not load generated TFLite schema: {schema_path}")
    schema = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(schema)
    return schema


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def rewrite(source: Path, output: Path) -> dict[str, Any]:
    manifest_path = output.with_suffix(".json")
    if not source.is_file():
        raise FileNotFoundError(source)
    if output.exists():
        raise FileExistsError(f"Refusing to overwrite existing model: {output}")
    if manifest_path.exists():
        raise FileExistsError(f"Refusing to overwrite existing manifest: {manifest_path}")

    schema = load_schema()
    source_bytes = source.read_bytes()
    model = schema.ModelT.InitFromObj(schema.Model.GetRootAsModel(source_bytes, 0))
    if len(model.subgraphs) != 1:
        raise RuntimeError(f"Expected a single-subgraph model, found {len(model.subgraphs)}")

    subgraph = model.subgraphs[0]
    original_operators = list(subgraph.operators)
    users: dict[int, list[int]] = defaultdict(list)
    for operator_index, operator in enumerate(original_operators):
        for raw_tensor_index in operator.inputs if operator.inputs is not None else []:
            tensor_index = int(raw_tensor_index)
            if tensor_index >= 0:
                users[tensor_index].append(operator_index)

    output_indices = {int(index) for index in subgraph.outputs}
    input_indices = {int(index) for index in subgraph.inputs}
    float16 = int(schema.TensorType.FLOAT16)
    float32 = int(schema.TensorType.FLOAT32)
    candidates: dict[int, int] = {}

    for tensor_index, tensor in enumerate(subgraph.tensors):
        if int(tensor.type) != float16 or tensor_index in output_indices or tensor_index in input_indices:
            continue
        buffer_index = int(tensor.buffer)
        if buffer_index <= 0 or buffer_index >= len(model.buffers):
            continue
        raw_buffer = model.buffers[buffer_index].data
        if raw_buffer is None or len(raw_buffer) == 0 or not users.get(tensor_index):
            continue
        expected_values = math.prod(int(dimension) for dimension in tensor.shape)
        if len(raw_buffer) != expected_values * np.dtype("<f2").itemsize:
            raise ValueError(
                f"FLOAT16 tensor {tensor_index} has {len(raw_buffer)} bytes; "
                f"shape requires {expected_values * 2}"
            )
        candidates[tensor_index] = buffer_index

    if not candidates:
        raise RuntimeError("No used FLOAT16 constant tensors were found.")

    dequantized_tensor: dict[int, int] = {}
    for tensor_index in candidates:
        source_tensor = subgraph.tensors[tensor_index]
        result_tensor = copy.copy(source_tensor)
        result_tensor.type = float32
        result_tensor.buffer = 0
        result_tensor.quantization = None
        result_tensor.isVariable = False
        result_tensor.sparsity = None
        result_tensor.externalBuffer = 0
        name = result_tensor.name or f"constant_{tensor_index}".encode("utf-8")
        if isinstance(name, str):
            name = name.encode("utf-8")
        result_tensor.name = name + b"/fp32_from_fp16"
        dequantized_tensor[tensor_index] = len(subgraph.tensors)
        subgraph.tensors.append(result_tensor)

    original_tensor_count = len(subgraph.tensors) - len(candidates)
    for tensor_index, tensor in enumerate(subgraph.tensors[:original_tensor_count]):
        if int(tensor.type) != float16 or tensor_index in candidates:
            continue
        buffer_index = int(tensor.buffer)
        has_constant_data = (
            0 < buffer_index < len(model.buffers)
            and model.buffers[buffer_index].data is not None
            and len(model.buffers[buffer_index].data) > 0
        )
        if not has_constant_data:
            tensor.type = float32

    dequantize_code = schema.OperatorCodeT()
    dequantize_code.deprecatedBuiltinCode = int(schema.BuiltinOperator.DEQUANTIZE)
    dequantize_code.builtinCode = int(schema.BuiltinOperator.DEQUANTIZE)
    dequantize_code.version = 2
    dequantize_code.customCode = None
    dequantize_opcode_index = len(model.operatorCodes)
    model.operatorCodes.append(dequantize_code)

    insert_before: dict[int, list[Any]] = defaultdict(list)
    for tensor_index, output_index in dequantized_tensor.items():
        consumer_indices = users.get(tensor_index, [])
        if not consumer_indices:
            raise RuntimeError(f"FLOAT16 constant tensor {tensor_index} has no consumers")
        dequantize_operator = schema.OperatorT()
        dequantize_operator.opcodeIndex = dequantize_opcode_index
        dequantize_operator.inputs = np.asarray([tensor_index], dtype=np.int32)
        dequantize_operator.outputs = np.asarray([output_index], dtype=np.int32)
        insert_before[min(consumer_indices)].append(dequantize_operator)

    updated_operators = []
    for operator_index, operator in enumerate(original_operators):
        updated_operators.extend(insert_before.get(operator_index, []))
        if operator.inputs is not None:
            operator.inputs = np.asarray(
                [
                    dequantized_tensor.get(int(index), int(index)) if int(index) >= 0 else int(index)
                    for index in operator.inputs
                ],
                dtype=np.int32,
            )
        updated_operators.append(operator)
    subgraph.operators = updated_operators

    # Keep CAST metadata consistent with the promoted input/output tensor types.
    cast_code = int(schema.BuiltinOperator.CAST)
    for operator in subgraph.operators:
        code = model.operatorCodes[operator.opcodeIndex]
        if int(code.builtinCode) != cast_code:
            continue
        if (
            operator.builtinOptions is None
            or operator.inputs is None
            or len(operator.inputs) != 1
            or operator.outputs is None
            or len(operator.outputs) != 1
        ):
            raise RuntimeError("Unexpected CAST operator structure.")
        operator.builtinOptions.inDataType = int(subgraph.tensors[int(operator.inputs[0])].type)
        operator.builtinOptions.outDataType = int(subgraph.tensors[int(operator.outputs[0])].type)

    builder = flatbuffers.Builder(1024)
    root = model.Pack(builder)
    builder.Finish(root, file_identifier=b"TFL3")
    packed = bytes(builder.Output())

    # Reparse the finished flatbuffer and check its public tensor contract.
    verified = schema.ModelT.InitFromObj(schema.Model.GetRootAsModel(packed, 0))
    verified_graph = verified.subgraphs[0]
    if len(verified_graph.inputs) != 1 or len(verified_graph.outputs) != 1:
        raise RuntimeError("Unexpected input/output count after rewriting.")
    input_tensor = verified_graph.tensors[int(verified_graph.inputs[0])]
    output_tensor = verified_graph.tensors[int(verified_graph.outputs[0])]
    if int(input_tensor.type) != float32 or int(output_tensor.type) != float32:
        raise RuntimeError("Rewritten public input/output tensors are not FLOAT32.")

    operator_counts = defaultdict(int)
    for operator in verified_graph.operators:
        code = verified.operatorCodes[operator.opcodeIndex]
        operator_counts[int(code.builtinCode)] += 1
    if operator_counts[int(schema.BuiltinOperator.DEQUANTIZE)] < len(candidates):
        raise RuntimeError("Not every FP16 constant received a DEQUANTIZE operator.")

    output.parent.mkdir(parents=True, exist_ok=True)
    report = {
        "model_source": "ZhengPeng7/BiRefNet_lite",
        "license": "MIT",
        "transform": "FP16 constant weights with DEQUANTIZE to FP32; runtime activations remain FP32",
        "model": {
            "file": output.name,
            "bytes": len(packed),
            "sha256": sha256(packed),
            "precision": "float16 weights / float32 activations",
            "input_shape": [int(value) for value in input_tensor.shape],
            "input_dtype": "float32",
            "output_shape": [int(value) for value in output_tensor.shape],
            "output_dtype": "float32",
        },
        "source": str(source),
        "source_bytes": len(source_bytes),
        "source_sha256": sha256(source_bytes),
        "float16_constants_dequantized": len(candidates),
        "dequantize_operators": operator_counts[int(schema.BuiltinOperator.DEQUANTIZE)],
    }
    output.write_bytes(packed)
    manifest_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    report = rewrite(args.source, args.output)
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
